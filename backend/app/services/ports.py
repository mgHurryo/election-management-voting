from datetime import datetime
from types import TracebackType
from typing import Protocol, Self

from app.models.elections import CandidateDetails, ElectionDetails
from app.models.identity import UserAccount, UserIdentity
from app.models.roster import ElectionSnapshot, VoterMembership


class IdentityRepository(Protocol):
    def by_username(self, username: str) -> UserAccount | None: ...
    def by_id(self, user_id: int) -> UserAccount | None: ...


class HealthRepository(Protocol):
    def ping(self) -> None: ...


class RosterRepository(Protocol):
    def election(
        self, election_id: int, *, for_update: bool = False
    ) -> ElectionSnapshot | None: ...
    def membership(self, election_id: int, user_id: int) -> VoterMembership | None: ...
    def memberships(
        self, election_id: int, offset: int, limit: int
    ) -> tuple[list[VoterMembership], int]: ...
    def add(self, election_id: int, user_id: int, vote_quota: int) -> None: ...
    def remove(self, election_id: int, user_id: int) -> None: ...
    def participation_count(self, election_id: int, user_id: int) -> int: ...


class ElectionsRepository(Protocol):
    def create(
        self,
        *,
        title: str,
        position_title: str,
        description: str | None,
        created_by: int,
        starts_at: datetime,
        ends_at: datetime,
        voter_ids: list[int],
    ) -> ElectionDetails: ...
    def election(self, election_id: int, *, for_update: bool = False) -> ElectionDetails | None: ...
    def elections(
        self,
        *,
        user: UserIdentity,
        status: str | None,
        offset: int,
        limit: int,
    ) -> tuple[list[ElectionDetails], int]: ...
    def update_election(self, election_id: int, changes: dict[str, object]) -> ElectionDetails: ...
    def update_status(self, election_id: int, status: str) -> ElectionDetails: ...
    def drafts_window_started(self, now: datetime) -> list[int]: ...
    def open_window_ended(self, now: datetime) -> list[int]: ...
    def has_active_voter(self, election_id: int) -> bool: ...
    def has_valid_candidates(self, election_id: int) -> bool: ...
    def candidates(
        self, election_id: int, offset: int, limit: int
    ) -> tuple[list[CandidateDetails], int]: ...
    def candidate(
        self, election_id: int, candidate_id: int, *, for_update: bool = False
    ) -> CandidateDetails | None: ...
    def add_candidate(
        self,
        election_id: int,
        *,
        name: str,
        description: str,
        photo_url: str | None,
        display_order: int,
    ) -> CandidateDetails: ...
    def update_candidate(
        self, election_id: int, candidate_id: int, changes: dict[str, object]
    ) -> CandidateDetails: ...
    def candidate_is_referenced(self, election_id: int, candidate_id: int) -> bool: ...
    def delete_candidate(self, election_id: int, candidate_id: int) -> None: ...
    def has_voter(self, election_id: int, user_id: int) -> bool: ...


class VotingRepository(Protocol):
    def election(
        self, election_id: int, *, for_update: bool = False, for_share: bool = False
    ) -> ElectionDetails | None: ...
    def vote_quota(self, election_id: int, user_id: int) -> int | None: ...
    def locked_vote_quota(self, election_id: int, user_id: int) -> int | None: ...
    def participation_usage(
        self, election_id: int, user_id: int, *, for_update: bool = False
    ) -> tuple[int, int]: ...
    def all_candidates(self, election_id: int) -> list[CandidateDetails]: ...
    def record_vote(
        self, election_id: int, user_id: int, vote_sequence: int, candidate_id: int
    ) -> None: ...


class UnitOfWork(Protocol):
    users: IdentityRepository
    health: HealthRepository
    roster: RosterRepository
    elections: ElectionsRepository
    voting: VotingRepository

    def __enter__(self) -> Self: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...
    def commit(self) -> None: ...
